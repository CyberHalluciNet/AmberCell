#!/bin/bash
set -euo pipefail

LOG_FIFO="${AMBER_MONGO_LOG_FIFO:-/run/amber/log/mongo.fifo}"
mkdir -p "$(dirname "$LOG_FIFO")"
if [ ! -p "$LOG_FIFO" ]; then
  rm -f "$LOG_FIFO"
  mkfifo "$LOG_FIFO"
  chmod 666 "$LOG_FIFO" 2>/dev/null || true
fi

exec docker-entrypoint.sh mongod --bind_ip_all 2>&1 | while IFS= read -r line; do
  printf '%s\n' "$line" >>"$LOG_FIFO" 2>/dev/null || true
  printf '%s\n' "$line"
done
